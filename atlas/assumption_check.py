"""Check the reported-controls assumptions (Table E) against real building graphs.

The readiness framework's census (tables/R_reference_set.csv) holds 45 real Brick graphs of buildings with
automation systems, each with the stream classes it declares (typed points) and links (points with
a time series). A Table E row says "a building reporting control X has stream class Y". The census
cannot test X -> Y directly (it records no CBECS answers), but it shows how common each declared
class Y is in real automated buildings, and how often a declared Y is linked to data. A row whose
class is rare in real automated buildings rests on weak evidence, whatever its engineering logic.

    python -m atlas.assumption_check      -> results/reference_set/assumption_check.{md,csv}
"""
from __future__ import annotations

import pandas as pd

from atlas import config, declared

OUT = config.RESULTS / "reference_set"


def class_support() -> pd.DataFrame:
    c = declared.census()
    split = lambda s: set() if s == "-" else set(s.split("+"))
    dec = c.streams_declared.map(split)
    lnk = c.streams_linked.map(split)
    n_all = len(c)
    n_any = int((dec.map(len) > 0).sum())
    classes = sorted(set().union(*dec))
    rows = []
    for k in classes:
        d = int(dec.map(lambda s: k in s).sum())
        l_ = int(lnk.map(lambda s: k in s).sum())
        rows.append({"class": k, "declared_in": d, "of_graphs": n_all, "declared_share": d / n_all,
                     "declared_share_of_graphs_declaring_any": d / n_any, "linked_in": l_,
                     "linked_given_declared": (l_ / d) if d else float("nan")})
    return pd.DataFrame(rows).set_index("class")


def row_support() -> pd.DataFrame:
    sup = class_support()
    out = []
    for r in declared.table_e():
        if r["streams"] == "-":
            continue
        for k in r["streams"].split("+"):
            s = sup.loc[k] if k in sup.index else None
            out.append({"row": r["id"], "reading": r["reading"], "declares": k,
                        "declared_in_census": f"{int(s.declared_in)}/{int(s.of_graphs)}" if s is not None else "0/45",
                        "declared_share": float(s.declared_share) if s is not None else 0.0,
                        "linked_given_declared": float(s.linked_given_declared) if s is not None else float("nan")})
    return pd.DataFrame(out)


def grade(share: float) -> str:
    return "common (≥ 50 %)" if share >= 0.5 else "present (10–50 %)" if share >= 0.1 else "rare (< 10 %)"


def build() -> pd.DataFrame:
    T = row_support()
    T["census_evidence"] = T.declared_share.map(grade)
    OUT.mkdir(parents=True, exist_ok=True)
    T.to_csv(OUT / "assumption_check.csv", index=False, float_format="%.3f")
    L = ["# Reported-controls assumptions against real automated buildings (the reference set's 45 graphs)", "",
         "Generated by `python -m atlas.assumption_check`. For each stream class a Table E row declares: in how "
         "many of the census's 45 real building graphs that class is declared, and, where declared, how often it "
         "is linked to a time series. The census buildings all have automation systems, so a class that is rare "
         "among them is weak support for a row that infers it from a reported control.", "",
         "| row | reading | declares | declared in census | share | evidence | linked when declared |",
         "|---|---|---|---:|---:|---|---:|"]
    for r in T.itertuples():
        lk = "—" if pd.isna(r.linked_given_declared) else f"{100 * r.linked_given_declared:.0f} %"
        L.append(f"| {r.row} | {r.reading} | {r.declares} | {r.declared_in_census} | "
                 f"{100 * r.declared_share:.0f} % | {r.census_evidence} | {lk} |")
    rare = T[T.declared_share < 0.1]
    L += ["", "Rows resting on a class that is rare in real automated buildings: "
          + (", ".join(f"{r.row} ({r.declares}, {r.declared_in_census})" for r in rare.itertuples()) or "none") + "."]
    (OUT / "assumption_check.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return T


if __name__ == "__main__":
    print(build().to_string())
